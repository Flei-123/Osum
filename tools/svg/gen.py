import sys

def fnv(s):
    h = 2166136261
    for b in s.encode():
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h

def load(path):
    rows = []
    for line in open(path, encoding="ascii").read().splitlines():
        if line.strip():
            k, v = line.split(None, 1)
            rows.append((k, v))
    return rows

def main(argv):
    rows = load(argv[0] if argv else "tools/svg/names.txt")
    hashes = {}
    for k, v in rows:
        h = fnv(v)
        if h in hashes:
            sys.exit("hash collision: %s %s" % (v, hashes[h]))
        hashes[h] = v
    out = ["// SPDX-License-Identifier: GPL-2.0-only", "// lib/svg/svgnames.fi -- GENERATED by tools/svg/gen.py from tools/svg/names.txt. Do not edit.", "profile kernel", ""]
    exp = ["hash_name"] + [k for k, _ in rows]
    out.append("export {")
    for i in range(0, len(exp), 6):
        out.append("    " + ", ".join(exp[i:i + 6]) + ("," if i + 6 < len(exp) else ""))
    out.append("}")
    out.append("")
    for k, v in rows:
        out.append("const %s: u64 = 0x%08X // %s" % (k, fnv(v), v))
    out.append("")
    out += [
        "fn hash_name(p: u64, n: u64) -> u64 {",
        "    var h: u64 = 2166136261",
        "    var i: u64 = 0",
        "    while i < n {",
        "        h = ((h ^ ((__mmio_read8((p + i) as *mut u8)) as u64)) *% 16777619) & 0xFFFFFFFF",
        "        i = i + 1",
        "    }",
        "    return h",
        "}",
    ]
    sys.stdout.write("\n".join(out) + "\n")

if __name__ == "__main__":
    main(sys.argv[1:])
