import re, sys, pathlib
root = pathlib.Path(sys.argv[1])
names = []
for f in sorted((root / "lib/vulkan").glob("vk*.fi")):
    if f.name in ("vkproc.fi", "vkobj.fi"):
        continue
    names += re.findall(r"^fn (vk\w+)\(", f.read_text(), re.M)
def h(s):
    v = 0
    for c in s.encode():
        v = (v * 31 + c) & 0xFFFFFFF
    return v
hs = {}
for n in names:
    assert h(n) not in hs, n
    hs[h(n)] = n
mods = sorted({f.stem for f in (root / "lib/vulkan").glob("vk*.fi") if f.stem not in ("vkproc", "vkobj")})
out = ["// SPDX-License-Identifier: GPL-2.0-only", "// generated by tools/vulkan/genproc.py -- do not edit", "import std.rt"]
out += [f"import vulkan.{m}" for m in mods]
out += ["", "export { vkGetInstanceProcAddr, vkGetDeviceProcAddr, vk_icdGetInstanceProcAddr, vk_icdNegotiateLoaderICDInterfaceVersion }", "",
        "fn name_hash(p: u64) -> u64 {", "    var v: u64 = 0 as u64", "    var i: usize = 0",
        "    while rt.ld8(p, i) != 0 as u8 {", "        v = (v * 31 as u64 + (rt.ld8(p, i) as u64)) & 0xFFFFFFF as u64", "        i = i + 1", "    }", "    return v", "}", "",
        "fn lookup(p: u64) -> u64 {", "    if p == 0 as u64 { return 0 as u64 }", "    let h: u64 = name_hash(p)"]
for n in names:
    mod = next(m for m in mods if re.search(rf"^fn {n}\(", (root / f"lib/vulkan/{m}.fi").read_text(), re.M))
    out.append(f"    if h == {h(n)} as u64 {{ return rt.ld64({mod}.{n} as u64, 0) }}")
for n in ("vkGetInstanceProcAddr", "vkGetDeviceProcAddr"):
    assert h(n) not in hs, n
    out.append(f"    if h == {h(n)} as u64 {{ return rt.ld64({n} as u64, 0) }}")
out += ["    return 0 as u64", "}", "",
        "#[export_c]", "fn vkGetInstanceProcAddr(inst: u64, name: u64) -> u64 {", "    return lookup(name)", "}", "",
        "#[export_c]", "fn vkGetDeviceProcAddr(dev: u64, name: u64) -> u64 {", "    return lookup(name)", "}", "",
        "#[export_c]", "fn vk_icdGetInstanceProcAddr(inst: u64, name: u64) -> u64 {", "    return lookup(name)", "}", "",
        "#[export_c]", "fn vk_icdNegotiateLoaderICDInterfaceVersion(version: u64) -> i32 {",
        "    if rt.ld32(version, 0) > 5 as u32 { rt.st32(version, 0, 5 as u32) }", "    return 0", "}"]
(root / "lib/vulkan/vkproc.fi").write_text("\n".join(out) + "\n")
print(len(names), "functions")
