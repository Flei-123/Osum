"""tools/hid/kbdgen.py -- generate the keyboard layout data of the kernel from the xkb data of the host.

  lib/keymap/kbdnames.fi       layout registry (count, names); in lib/ because user programs import it too
  kernel/drv/hid/kbdlay.fi     symbols per layout, key position and level (plain, shift, altgr, altgr+shift, and the same with caps lock)
  kernel/drv/hid/kbdcomb.fi    dead key spacing characters, dead key combinations, compose sequences

  python3 tools/hid/kbdgen.py            write the three files
  python3 tools/hid/kbdgen.py --check    exit 1 if a file on disk is stale
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xkbq

LAYOUTS = [
    ("us", "us", ""), ("de", "de", ""), ("uk", "gb", ""), ("fr", "fr", ""), ("es", "es", ""),
    ("it", "it", ""), ("ru", "ru", ""), ("us-intl", "us", "intl"), ("de-at", "at", ""),
    ("ch-de", "ch", ""), ("pt", "pt", ""), ("pt-br", "br", ""), ("pl", "pl", ""), ("tr", "tr", ""),
    ("nl", "nl", ""), ("ch-fr", "ch", "fr"), ("se", "se", ""),
]
SLOTS = (list(range(0x02, 0x0E)) + list(range(0x10, 0x1C)) + list(range(0x1E, 0x2A))
         + [0x2B] + list(range(0x2C, 0x36)) + [0x39, 0x56, 0x73])
DEAD_FLAG = 1 << 24
NAME_LEN = 8
SPACING_FIXED = {0xFE50: 0x60, 0xFE51: 0xB4, 0xFE52: 0x5E, 0xFE53: 0x7E, 0xFE54: 0xAF, 0xFE55: 0x2D8,
                 0xFE56: 0x2D9, 0xFE57: 0xA8, 0xFE58: 0x2DA, 0xFE59: 0x2DD, 0xFE5A: 0x2C7, 0xFE5B: 0xB8,
                 0xFE5C: 0x2DB}
DEAD_BASES = range(0x20, 0x2200)
COMPOSE_BASES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
TARGET = {"kbdnames.fi": "lib/keymap", "kbdlay.fi": "kernel/drv/hid", "kbdcomb.fi": "kernel/drv/hid"}
HEADER = "// SPDX-License-Identifier: GPL-2.0-only\n// GENERATED by tools/hid/kbdgen.py from the xkb data; do not edit.\n\nprofile kernel\n\n"


def entry_of(sym):
    if xkbq.DEAD_FIRST <= sym <= xkbq.DEAD_LAST:
        return DEAD_FLAG | (sym - xkbq.DEAD_FIRST)
    return xkbq.keysym_cp(sym)


def layout_symbols():
    out = []
    used_dead = set()
    for _name, xkb, variant in LAYOUTS:
        km = xkbq.Keymap(xkb, variant)
        rows = []
        for scan in SLOTS:
            row = []
            for caps in (0, 1):
                for altgr in (0, 1):
                    for shift in (0, 1):
                        e = entry_of(km.sym(scan, shift, altgr, caps))
                        if e & DEAD_FLAG:
                            used_dead.add(xkbq.DEAD_FIRST + (e & 0xFFFF))
                        row.append(e)
            rows.append(row)
        out.append(rows)
    return out, used_dead


def numbers(values, per_line=12):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ",".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def gen_names():
    names = []
    for name, _x, _v in LAYOUTS:
        raw = [ord(c) for c in name] + [0] * (NAME_LEN - len(name))
        assert len(name) < NAME_LEN
        names.extend(raw)
    o = [HEADER.rstrip("\n").replace("\n\nprofile kernel", ""), "", "export { COUNT, NAME_LEN, NONE, name_at, id_of }", ""]
    o.append("const COUNT: u64 = %d" % len(LAYOUTS))
    o.append("const NAME_LEN: u64 = %d" % NAME_LEN)
    o.append("const NONE: u64 = 0xFFFF")
    o.append("")
    o.append("static mut NAMES: [u8; %d] = [" % len(names))
    o.append(numbers(names, 16))
    o.append("]")
    o.append("")
    o.append("fn name_at(lay: u64, i: u64) -> u64 {")
    o.append("    if lay >= COUNT || i >= NAME_LEN {")
    o.append("        return 0")
    o.append("    }")
    o.append("    return (NAMES[(lay * NAME_LEN + i) as usize]) as u64")
    o.append("}")
    o.append("")
    o.append("fn same(lay: u64, p: u64) -> bool {")
    o.append("    var i: u64 = 0")
    o.append("    while i < NAME_LEN {")
    o.append("        let a: u64 = name_at(lay, i)")
    o.append("        let b: u64 = (*((p + i) as *mut u8)) as u64")
    o.append("        if a != b {")
    o.append("            return false")
    o.append("        }")
    o.append("        if a == 0 {")
    o.append("            return true")
    o.append("        }")
    o.append("        i = i + 1")
    o.append("    }")
    o.append("    return (*((p + NAME_LEN) as *mut u8)) == 0 as u8")
    o.append("}")
    o.append("")
    o.append("fn id_of(p: u64) -> u64 {")
    o.append("    var lay: u64 = 0")
    o.append("    while lay < COUNT {")
    o.append("        if same(lay, p) {")
    o.append("            return lay")
    o.append("        }")
    o.append("        lay = lay + 1")
    o.append("    }")
    o.append("    return NONE")
    o.append("}")
    return "\n".join(o) + "\n"


def gen_layouts(symbols):
    slot_of = [255] * 128
    for i, scan in enumerate(SLOTS):
        slot_of[scan] = i
    flat = []
    for rows in symbols:
        for row in rows:
            flat.extend(row)
    o = [HEADER.rstrip("\n"), "", "export { SLOTS, LEVELS, DEAD_FLAG, NO_SLOT, slot_of, sym }", ""]
    o.append("const SLOTS: u64 = %d" % len(SLOTS))
    o.append("const LEVELS: u64 = 8")
    o.append("const DEAD_FLAG: u64 = 0x%X" % DEAD_FLAG)
    o.append("const NO_SLOT: u64 = 255")
    o.append("")
    o.append("static mut SLOT_OF: [u8; 128] = [")
    o.append(numbers(slot_of, 16))
    o.append("]")
    o.append("")
    o.append("static mut SYMS: [u32; %d] = [" % len(flat))
    o.append(numbers(flat))
    o.append("]")
    o.append("")
    o.append("fn slot_of(code: u64) -> u64 {")
    o.append("    if code >= 128 {")
    o.append("        return NO_SLOT")
    o.append("    }")
    o.append("    return (SLOT_OF[code as usize]) as u64")
    o.append("}")
    o.append("")
    o.append("fn sym(lay: u64, slot: u64, level: u64) -> u64 {")
    o.append("    return (SYMS[((lay * SLOTS + slot) * LEVELS + level) as usize]) as u64")
    o.append("}")
    return "\n".join(o) + "\n"


def spacing_for(compose, sym):
    if sym in SPACING_FIXED:
        return SPACING_FIXED[sym]
    for second in (sym, xkbq.keysym_named("space")):
        cp = compose.single([sym, second])
        if cp:
            return cp
    return 0


def dead_pairs(compose, dead_syms):
    pairs = []
    for sym in sorted(dead_syms):
        ident = sym - xkbq.DEAD_FIRST
        for base in DEAD_BASES:
            ks = xkbq.cp_keysym(base)
            if not ks or base == 32:
                continue
            res = compose.single([sym, ks])
            if res and res != base:
                pairs.append(((ident << 42) | (base << 21) | res))
    return pairs


def compose_pairs(compose):
    pairs = []
    for a in COMPOSE_BASES:
        ka = xkbq.cp_keysym(a)
        for b in COMPOSE_BASES:
            kb = xkbq.cp_keysym(b)
            res = compose.single([xkbq.MULTI_KEY, ka, kb])
            if res:
                pairs.append((a << 42) | (b << 21) | res)
    return pairs


def dead_spacing(compose, used_dead):
    spacing = [0] * 64
    for sym in used_dead:
        spacing[sym - xkbq.DEAD_FIRST] = spacing_for(compose, sym)
    return spacing


def drop_unusable_dead(symbols, spacing):
    for rows in symbols:
        for row in rows:
            for i, e in enumerate(row):
                if e & DEAD_FLAG and spacing[e & 0xFFFF] == 0:
                    row[i] = 0


def gen_comb(compose, spacing, used_dead):
    dpairs = dead_pairs(compose, used_dead)
    cpairs = compose_pairs(compose)
    o = [HEADER.rstrip("\n"), "", "export { DEAD_IDS, DEAD_N, COMPOSE_N, DEAD_TAB, COMPOSE_TAB, SPACING }", ""]
    o.append("const DEAD_IDS: u64 = 64")
    o.append("const DEAD_N: u64 = %d" % len(dpairs))
    o.append("const COMPOSE_N: u64 = %d" % len(cpairs))
    o.append("")
    o.append("static mut SPACING: [u32; 64] = [")
    o.append(numbers(spacing, 16))
    o.append("]")
    o.append("")
    o.append("static mut DEAD_TAB: [u64; %d] = [" % len(dpairs))
    o.append(numbers(dpairs, 6))
    o.append("]")
    o.append("")
    o.append("static mut COMPOSE_TAB: [u64; %d] = [" % len(cpairs))
    o.append(numbers(cpairs, 6))
    o.append("]")
    return "\n".join(o) + "\n"


def generate():
    symbols, used_dead = layout_symbols()
    compose = xkbq.Compose()
    spacing = dead_spacing(compose, used_dead)
    drop_unusable_dead(symbols, spacing)
    used_dead = [s for s in used_dead if spacing[s - xkbq.DEAD_FIRST]]
    return {
        "kbdnames.fi": gen_names(),
        "kbdlay.fi": gen_layouts(symbols),
        "kbdcomb.fi": gen_comb(compose, spacing, used_dead),
    }


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.join(here, "..", "..")
    files = generate()
    if "--check" in sys.argv:
        stale = 0
        for name, text in files.items():
            path = os.path.join(root, TARGET[name], name)
            cur = open(path).read() if os.path.exists(path) else ""
            if cur != text:
                print("kbdgen: %s is stale" % name)
                stale = 1
        sys.exit(stale)
    for name, text in files.items():
        path = os.path.join(root, TARGET[name], name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(text)
        print("kbdgen: wrote %s (%d lines)" % (os.path.normpath(path), text.count("\n")))
