"""tools/hid/kbdgen.py -- generate kernel/drv/hid/kbdlay.fi (keyboard layouts UK/FR/ES/IT/RU).

Source of truth: the xkb data of the host (libxkbcommon, rules evdev, model pc105).
For every PC key position (set-1 scancode; evdev keycode = scancode, xkb keycode = +8) the
base, Shift and AltGr (level 3) character is read and written as a Firn `if` chain.
Only entries that DIFFER from the US table are emitted (the kernel falls back to the US
table for the rest). Dead keys become their spacing character (same rule as the German
layout in kbd.fi: "not dead").

  python3 tools/hid/kbdgen.py            write kernel/drv/hid/kbdlay.fi
  python3 tools/hid/kbdgen.py --check    exit 1 if the file on disk is stale
"""
import ctypes, ctypes.util, os, sys

LAYOUTS = [("uk", "gb", 2), ("fr", "fr", 3), ("es", "es", 4), ("it", "it", 5), ("ru", "ru", 6)]
# printable key positions of a PC keyboard (set-1 scancodes), plus 0x56 (ISO "<>" key)
KEYS = (list(range(0x02, 0x0E)) + list(range(0x10, 0x1C)) + list(range(0x1E, 0x29))
        + [0x29, 0x2B] + list(range(0x2C, 0x36)) + [0x56])
DEAD = {0xfe50: 0x60, 0xfe51: 0xB4, 0xfe52: 0x5E, 0xfe53: 0x7E, 0xfe54: 0xAF, 0xfe55: 0x2D8,
        0xfe56: 0x2D9, 0xfe57: 0xA8, 0xfe58: 0x2DA, 0xfe59: 0x2DD, 0xfe5a: 0x2C7, 0xfe5b: 0xB8,
        0xfe5c: 0x2DB}

class Names(ctypes.Structure):
    _fields_ = [(n, ctypes.c_char_p) for n in ("rules", "model", "layout", "variant", "options")]

lib = ctypes.CDLL(ctypes.util.find_library("xkbcommon"))
lib.xkb_context_new.restype = ctypes.c_void_p
lib.xkb_keymap_new_from_names.restype = ctypes.c_void_p
lib.xkb_keymap_new_from_names.argtypes = [ctypes.c_void_p, ctypes.POINTER(Names), ctypes.c_int]
lib.xkb_keymap_key_get_syms_by_level.argtypes = [ctypes.c_void_p, ctypes.c_uint32, ctypes.c_uint32,
    ctypes.c_uint32, ctypes.POINTER(ctypes.POINTER(ctypes.c_uint32))]
lib.xkb_keymap_key_get_syms_by_level.restype = ctypes.c_int
lib.xkb_keysym_to_utf32.restype = ctypes.c_uint32
lib.xkb_keysym_to_utf32.argtypes = [ctypes.c_uint32]
CTX = lib.xkb_context_new(0)

def table(layout):
    n = Names(b"evdev", b"pc105", layout.encode(), b"", b"")
    km = lib.xkb_keymap_new_from_names(CTX, ctypes.byref(n), 0)
    if not km:
        sys.exit("xkb: cannot compile layout " + layout)
    out = {}
    for sc in KEYS:
        row = []
        for level in (0, 1, 2):
            p = ctypes.POINTER(ctypes.c_uint32)()
            cnt = lib.xkb_keymap_key_get_syms_by_level(km, sc + 8, 0, level, ctypes.byref(p))
            cp = 0
            if cnt >= 1:
                sym = p[0]
                cp = DEAD.get(sym) or lib.xkb_keysym_to_utf32(sym)
                if cp < 32 or cp == 127:
                    cp = 0
            row.append(cp)
        out[sc] = row
    return out

def gen():
    us = table("us")
    o = []
    o.append("// SPDX-License-Identifier: GPL-2.0-only")
    o.append("// kernel/drv/hid/kbdlay.fi -- GENERATED by tools/hid/kbdgen.py from the xkb data (rules evdev,")
    o.append("// model pc105). DO NOT EDIT; run `python3 tools/hid/kbdgen.py`. Layouts: 2 uk, 3 fr, 4 es, 5 it, 6 ru.")
    o.append("// Each function returns a Unicode code point, or 0 = \"same as the US table\" (plain/shift) or")
    o.append("// \"no AltGr character\" (altgr). Dead keys are spacing characters, like the German layout.")
    o.append("")
    o.append("profile kernel")
    o.append("")
    o.append("export { plain, shift, altgr, NAME_LEN }")
    o.append("")
    o.append("const NAME_LEN: u64 = 2")
    o.append("")
    for lvl, nm in ((0, "plain"), (1, "shift"), (2, "altgr")):
        for (tag, xkb, num) in LAYOUTS:
            t = table(xkb)
            o.append("fn %s_%s(code: u64) -> u64 {" % (tag, nm))
            for sc in KEYS:
                cp = t[sc][lvl]
                if cp == 0:
                    continue
                if lvl < 2 and sc != 0x56 and cp == us[sc][lvl]:
                    continue
                o.append("    if code == 0x%02X {" % sc)
                o.append("        return 0x%04X" % cp)
                o.append("    }")
            o.append("    return 0")
            o.append("}")
            o.append("")
        o.append("fn %s(lay: u64, code: u64) -> u64 {" % nm)
        for (tag, xkb, num) in LAYOUTS:
            o.append("    if lay == %d {" % num)
            o.append("        return %s_%s(code)" % (tag, nm))
            o.append("    }")
        o.append("    return 0")
        o.append("}")
        o.append("")
    return "\n".join(o)

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "..", "kernel", "drv", "hid", "kbdlay.fi")
    text = gen()
    if "--check" in sys.argv:
        cur = open(path).read() if os.path.exists(path) else ""
        sys.exit(0 if cur == text else 1)
    open(path, "w").write(text)
    print("kbdgen: wrote %s (%d lines)" % (os.path.normpath(path), text.count("\n") + 1))
