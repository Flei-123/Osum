#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-only
# tools/alpine/mkapk.py -- build a tiny LOCAL apk repository (APKv2 package + APKINDEX.tar.gz), stdlib only.
#
#   python3 -I mkapk.py <outdir> [--arch=x86_64]
#
# Writes <outdir>/<arch>/APKINDEX.tar.gz and <outdir>/<arch>/osumhello-1.0-r0.apk, and prints the list of
# "<image path>=<host file>" spec entries (relative to the repo root) on stdout, one per line.
# The package holds /usr/bin/osumhello (a shell script) and /usr/share/osumhello/data.txt; it has no dependencies, so
# `apk add --no-network --allow-untrusted --repository /repo osumhello` needs nothing but the repository.
import base64, gzip, hashlib, io, os, sys, tarfile, time

ARCH = "x86_64"
PKG = "osumhello"
VER = "1.0-r0"
MTIME = 1760400000  # fixed: the repository is reproducible


def tar_cut(members):
    """ustar stream WITHOUT the two terminating zero blocks (abuild-tar --cut): gzip streams of one .apk concatenate."""
    bio = io.BytesIO()
    tf = tarfile.open(fileobj=bio, mode="w", format=tarfile.USTAR_FORMAT)
    for name, data, mode, kind in members:
        ti = tarfile.TarInfo(name)
        ti.mtime = MTIME
        ti.uid = ti.gid = 0
        ti.uname = ti.gname = "root"
        ti.mode = mode
        if kind == "dir":
            ti.type = tarfile.DIRTYPE
            tf.addfile(ti)
        else:
            ti.size = len(data)
            tf.addfile(ti, io.BytesIO(data))
    end = tf.offset
    return bio.getvalue()[:end]


def gz(data):
    bio = io.BytesIO()
    with gzip.GzipFile(fileobj=bio, mode="wb", mtime=0, compresslevel=9) as g:
        g.write(data)
    return bio.getvalue()


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    for a in sys.argv[1:]:
        if a.startswith("--arch="):
            global ARCH
            ARCH = a[7:]
    out = args[0]
    script = b"#!/bin/sh\necho osumhello 1.0\n"
    payload = b"hello from the local mirror\n"
    data_members = [
        ("usr", b"", 0o755, "dir"),
        ("usr/bin", b"", 0o755, "dir"),
        ("usr/bin/osumhello", script, 0o755, "file"),
        ("usr/share", b"", 0o755, "dir"),
        ("usr/share/osumhello", b"", 0o755, "dir"),
        ("usr/share/osumhello/data.txt", payload, 0o644, "file"),
    ]
    # the data segment keeps its end-of-archive blocks (it is the last one); the control segment must not
    data_tar = io.BytesIO()
    tf = tarfile.open(fileobj=data_tar, mode="w", format=tarfile.PAX_FORMAT)
    for name, data, mode, kind in data_members:
        ti = tarfile.TarInfo(name)
        if kind != "dir":
            # apk-tools 3 refuses a file without the embedded checksum ("file format is obsolete")
            ti.pax_headers = {"APK-TOOLS.checksum.SHA1": hashlib.sha1(data).hexdigest()}
        ti.mtime = MTIME
        ti.uid = ti.gid = 0
        ti.uname = ti.gname = "root"
        ti.mode = mode
        if kind == "dir":
            ti.type = tarfile.DIRTYPE
            tf.addfile(ti)
        else:
            ti.size = len(data)
            tf.addfile(ti, io.BytesIO(data))
    tf.close()
    data_gz = gz(data_tar.getvalue())
    isize = len(script) + len(payload)
    pkginfo = (
        "# Generated by tools/alpine/mkapk.py\n"
        f"pkgname = {PKG}\npkgver = {VER}\npkgdesc = Osum local mirror test package\n"
        f"url = https://osum.invalid/\nbuilddate = {MTIME}\npackager = osum\nsize = {isize}\n"
        f"arch = {ARCH}\norigin = {PKG}\nlicense = GPL-2.0-only\n"
        f"datahash = {hashlib.sha256(data_gz).hexdigest()}\n"
    ).encode()
    ctl_gz = gz(tar_cut([(".PKGINFO", pkginfo, 0o644, "file")]))
    apk = ctl_gz + data_gz
    d = os.path.join(out, ARCH)
    os.makedirs(d, exist_ok=True)
    apkname = f"{PKG}-{VER}.apk"
    with open(os.path.join(d, apkname), "wb") as f:
        f.write(apk)
    csum = "Q1" + base64.b64encode(hashlib.sha1(ctl_gz).digest()).decode()
    index = (
        f"C:{csum}\nP:{PKG}\nV:{VER}\nA:{ARCH}\nS:{len(apk)}\nI:{isize}\n"
        f"T:Osum local mirror test package\nU:https://osum.invalid/\nL:GPL-2.0-only\no:{PKG}\nm:osum\nt:{MTIME}\n\n"
    ).encode()
    idx_gz = gz(tar_cut([("DESCRIPTION", b"osum local mirror\n", 0o644, "file"), ("APKINDEX", index, 0o644, "file")]))
    with open(os.path.join(d, "APKINDEX.tar.gz"), "wb") as f:
        f.write(idx_gz)
    print(f"/{ARCH}/APKINDEX.tar.gz={os.path.join(d, 'APKINDEX.tar.gz')}")
    print(f"/{ARCH}/{apkname}={os.path.join(d, apkname)}")


main()
