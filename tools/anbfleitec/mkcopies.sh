# tools/anbfleitec/mkcopies.sh -- (re)generate kernel/app/{kbig,ksha512,ked25519}.fi
# from lib/crypto/{big,sha512,ed25519}.fi.
#
# Why copies: Firn names a module by the LAST import segment. The TLS stack
# of `knetz` pulls in `std.crypto.big` and `std.crypto.sha512` (other API),
# so `import crypto.big` / `import crypto.sha512` inside the account program
# clash with them ("module 'sha512' has no element 'hash'"). The copies carry
# other module names; the code is byte-identical apart from those names.
#
#   tools/anbfleitec/mkcopies.sh          write the copies
#   tools/anbfleitec/mkcopies.sh --check  exit 1 if a copy is stale
set -euo pipefail
cd "$(dirname "$0")/../.."
gen() { # <src> <dst> <title>
    {
        printf '// GENERATED by tools/anbfleitec/mkcopies.sh from %s -- do not edit.\n' "$1"
        sed -e 's/\bcrypto\.big\b/kbig/g' -e 's/\bcrypto\.sha512\b/ksha512/g' \
            -e 's/\bbig\.\([A-Za-z_]\)/kbig.\1/g' -e 's/\bsha512\.\([A-Za-z_]\)/ksha512.\1/g' "$1"
    } > "$2"
}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
gen lib/crypto/big.fi "$T/kbig.fi"
gen lib/crypto/sha512.fi "$T/ksha512.fi"
gen lib/crypto/ed25519.fi "$T/ked25519.fi"
rc=0
for f in kbig ksha512 ked25519; do
    if [ "${1:-}" = "--check" ]; then
        cmp -s "$T/$f.fi" "kernel/app/$f.fi" || { echo "STALE kernel/app/$f.fi"; rc=1; }
    else
        cp "$T/$f.fi" "kernel/app/$f.fi"
    fi
done
exit $rc
