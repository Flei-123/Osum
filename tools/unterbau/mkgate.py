"""mkgate.py <old-results> <new-results> <outdir>

  accept.txt  every check that passes on the NEW kernel and does not depend on timing -- "what works today must keep working"
  fixed.txt   every check that does NOT pass on the old kernel (main before the round) and passes on the new one -- the counter-proof list
Run it after a full run of tools/unterbau/run.sh (UB_RESULT=... and, for the old kernel, OLDK=<kernel of the old tree> UB_OLD_RESULT=...)."""
import sys, os
TIMING = ("timedwait", "advances_with_sleep", "spawn_returns_before", "timerfd", "blocks_until_event", "alarm_fires", "setitimer", "interrupts_nanosleep",
          "sigsuspend", "periodic", "sigchld", "churn", "wait_wnohang", "stress", "2_threads", "24_threads", "committed_mib", "tmpfile")

def load(p):
    d = {}
    for l in open(p, errors="replace"):
        a = l.rstrip("\n").split(" ", 2)
        if len(a) >= 2 and "." in a[0] and a[1] in ("PASS", "FAIL", "GAP"):
            d.setdefault(a[0], a[1])
    return d

old, new, out = load(sys.argv[1]), load(sys.argv[2]), sys.argv[3]
acc = [n for n, v in new.items() if v == "PASS" and not any(t in n for t in TIMING)]
fix = [n for n, v in new.items() if v == "PASS" and old.get(n, "GAP") != "PASS" and not any(t in n for t in TIMING)]
open(os.path.join(out, "accept.txt"), "w").write("# checks that pass on the kernel of this round (generated by mkgate.py): what works today must keep working\n" + "\n".join(acc) + "\n")
open(os.path.join(out, "fixed.txt"), "w").write("# checks that do NOT pass on the kernel from before the round and do now: the counter-proof list of run.sh (OLDK=...)\n" + "\n".join(fix) + "\n")
print("accept: %d  fixed: %d" % (len(acc), len(fix)))
