import reportfile

DEVICES = [
    ("touchpad-045e-09af", 0x045E, 0x09AF, 2, 0),
    ("touchscreen-045e-0c32", 0x045E, 0x0C32, 1, 0),
    ("pen-045e-0c32", 0x045E, 0x0C32, 3, 0),
    ("inputmode-045e-09af", 0x045E, 0x09AF, 0, 0),
    ("hybrid-touch", 0x1234, 0x0010, 1, 0),
]
HYBRID = "hybrid-touch"
HYBRID_SLOTS = 2
SYNTHETIC = os.path.join(HERE, "corpus", "synthetic")
INPUTMODE = "inputmode-045e-09af"
I2C_CMDREG = 5
I2C_DATAREG = 6

SCREEN_W = 1024
SCREEN_H = 768
STEP_MS = 20
START_MS = 100000
NORM_MAX = 65535

T_DOWN, T_MOVE, T_UP = 1, 2, 3
F_PALM, F_BARREL, F_ERASER, F_HOVER = 1, 2, 4, 8
Q_INVERT_X, Q_INVERT_Y, Q_SINGLE_TOUCH, Q_IGNORE = 2, 4, 16, 32
FAKE_VID = 0x1234
FAKE_PID = 0x0001
FAKE_FLAGS = Q_INVERT_X | Q_INVERT_Y
SINGLE_PID = 0x0002
IGNORE_PID = 0x0003


def read_hex(name):
    base = SYNTHETIC if name == HYBRID else CORPUS
    with open(os.path.join(base, name + ".desc.hex")) as f:
        return bytes.fromhex(f.read().strip())


def feature_reports(device):
    with open(os.path.join(CORPUS, "reports.txt")) as f:
        lines = reportfile.parse_file(f.read())
    return [bytes.fromhex(l.hex) for l in lines if l.device == device and l.name.startswith("feat-")]


def i2c_frame(rid, payload):
    low = rid if rid < 15 else 15
    out = [I2C_CMDREG & 255, I2C_CMDREG >> 8, (3 << 4) | low, 3]
    if rid >= 15:
        out.append(rid)
    out += [I2C_DATAREG & 255, I2C_DATAREG >> 8]
    size = 2 + len(payload) + (1 if rid else 0)
    out += [size & 255, size >> 8]
    if rid:
        out.append(rid)
    return bytes(out) + bytes(payload)


def inmode_expected():
    lines = []
    for rep in feature_reports(INPUTMODE):
        rid, payload = rep[0], rep[1:]
        lines.append("corpus: inmode rid=%d data=%s" % (rid, ",".join(str(b) for b in payload)))
        lines.append("corpus: i2c %s" % ",".join(str(b) for b in i2c_frame(rid, payload)))
    return lines


def input_reports():
    with open(os.path.join(CORPUS, "reports.txt")) as f:
        lines = reportfile.parse_file(f.read())
    with open(os.path.join(SYNTHETIC, "reports.txt")) as f:
        lines += reportfile.parse_file(f.read())
    result = {}
    for line in lines:
        if line.name.startswith("feat-"):
            continue
        result.setdefault(line.device, []).append(line)
    return result


def hybrid_frames(lines):
    frames = []
    open_frame = None
    left = 0
    for line in lines:
        v = line.values
        slots = [(v["contact%d.id" % i], v["contact%d.x" % i], v["contact%d.y" % i], v["contact%d.tip" % i], 1)
                 for i in range(HYBRID_SLOTS)]
        count = v["count"]
        if open_frame is not None and count == 0:
            take = min(HYBRID_SLOTS, left)
            open_frame += slots[:take]
            left -= take
            if left == 0:
                frames.append(open_frame)
                open_frame = None
        elif count > HYBRID_SLOTS:
            open_frame = slots[:]
            left = count - HYBRID_SLOTS
        else:
            open_frame = None
            frames.append(slots[:count])
    return frames


def pack_words(data):
    words = []
    for i in range(0, len(data), 8):
        chunk = data[i:i + 8]
        words.append(int.from_bytes(chunk.ljust(8, b"\0"), "little"))
    return words


def word_array(data):
    words = pack_words(data)
    return ", ".join("0x%X" % w for w in words), len(words)


def name_word(name):
    return int.from_bytes(name[:8].ljust(8).encode("ascii"), "little")


def generate():
    reports = input_reports()
    descs = [read_hex(d[0]) for d in DEVICES]
    blobs = []
    for d, data in zip(DEVICES, descs):
        blobs.append((d, data))
    flat = []
    rep_meta = []
    for di, d in enumerate(DEVICES):
        for line in reports.get(d[0], []):
            raw = bytes.fromhex(line.hex)
            rep_meta.append((di, len(flat), len(raw)))
            flat.extend(raw)
    out = []
    out.append("// SPDX-License-Identifier: GPL-2.0-only")
    out.append("// GENERATED by tools/input/corpus_kernel.py gen -- do not edit. Source: tools/input/corpus/holo-laptop-3/")
    out.append("")
    out.append("profile kernel")
    out.append("")
    out.append("export { device_count, device_name, device_vid, device_pid, device_len, device_load,")
    out.append("    report_count, report_device, report_len, report_load }")
    out.append("")
    out.append("const DEVICES: u64 = %d" % len(DEVICES))
    out.append("const REPORTS: u64 = %d" % len(rep_meta))
    out.append("")
    out.append("fn device_count() -> u64 {")
    out.append("    return DEVICES")
    out.append("}")
    out.append("")
    out.append("fn device_name(i: u64) -> u64 {")
    out.append("    var t: [u64; %d] = [%s]" % (len(DEVICES), ", ".join("0x%X" % name_word(d[0]) for d in DEVICES)))
    out.append("    if i >= DEVICES {")
    out.append("        return 0")
    out.append("    }")
    out.append("    return t[i as usize]")
    out.append("}")
    out.append("")
    for fname, idx in (("device_vid", 1), ("device_pid", 2)):
        out.append("fn %s(i: u64) -> u64 {" % fname)
        out.append("    var t: [u64; %d] = [%s]" % (len(DEVICES), ", ".join("0x%X" % d[idx] for d in DEVICES)))
        out.append("    if i >= DEVICES {")
        out.append("        return 0")
        out.append("    }")
        out.append("    return t[i as usize]")
        out.append("}")
        out.append("")
    out.append("fn device_len(i: u64) -> u64 {")
    out.append("    var t: [u64; %d] = [%s]" % (len(DEVICES), ", ".join(str(len(x)) for x in descs)))
    out.append("    if i >= DEVICES {")
    out.append("        return 0")
    out.append("    }")
    out.append("    return t[i as usize]")
    out.append("}")
    out.append("")
    offs = []
    allbytes = b""
    for data in descs:
        offs.append(len(allbytes))
        allbytes += data
    arr, n = word_array(allbytes)
    out.append("fn device_load(i: u64, dst: u64) -> u64 {")
    out.append("    var w: [u64; %d] = [%s]" % (n, arr))
    out.append("    var off: [u64; %d] = [%s]" % (len(DEVICES), ", ".join(str(o) for o in offs)))
    out.append("    let len: u64 = device_len(i)")
    out.append("    var k: u64 = 0")
    out.append("    while k < len {")
    out.append("        let at: u64 = off[i as usize] + k")
    out.append("        kstate.set8(dst + k, ((w[(at / 8) as usize] >> ((at % 8) * 8)) & 0xFF) as u8)")
    out.append("        k = k + 1")
    out.append("    }")
    out.append("    return len")
    out.append("}")
    out.append("")
    out.append("fn report_count() -> u64 {")
    out.append("    return REPORTS")
    out.append("}")
    out.append("")
    out.append("fn report_device(i: u64) -> u64 {")
    out.append("    var t: [u64; %d] = [%s]" % (len(rep_meta), ", ".join(str(m[0]) for m in rep_meta)))
    out.append("    if i >= REPORTS {")
    out.append("        return 0")
    out.append("    }")
    out.append("    return t[i as usize]")
    out.append("}")
    out.append("")
    out.append("fn report_len(i: u64) -> u64 {")
    out.append("    var t: [u64; %d] = [%s]" % (len(rep_meta), ", ".join(str(m[2]) for m in rep_meta)))
    out.append("    if i >= REPORTS {")
    out.append("        return 0")
    out.append("    }")
    out.append("    return t[i as usize]")
    out.append("}")
    out.append("")
    arr, n = word_array(bytes(flat))
    out.append("fn report_load(i: u64, dst: u64) -> u64 {")
    out.append("    var w: [u64; %d] = [%s]" % (n, arr))
    out.append("    var off: [u64; %d] = [%s]" % (len(rep_meta), ", ".join(str(m[1]) for m in rep_meta)))
    out.append("    let len: u64 = report_len(i)")
    out.append("    var k: u64 = 0")
    out.append("    while k < len {")
    out.append("        let at: u64 = off[i as usize] + k")
    out.append("        kstate.set8(dst + k, ((w[(at / 8) as usize] >> ((at % 8) * 8)) & 0xFF) as u8)")
    out.append("        k = k + 1")
    out.append("    }")
    out.append("    return len")
    out.append("}")
    text = "\n".join(out) + "\n"
    text = text.replace("profile kernel\n", "profile kernel\n\nimport lib.kstate\n", 1)
    with open(OUT_FI, "w") as f:
        f.write(text)
    return OUT_FI


def norm(v, lo, hi):
    if hi <= lo:
        return 0
    c = min(max(v, lo), hi)
    return ((c - lo) * NORM_MAX) // (hi - lo)


def to_px(n, size):
    return (n * (size - 1)) // NORM_MAX


RANGES = {
    "touchpad-045e-09af": (0, 2227, 0, 1459),
    "touchscreen-045e-0c32": (0, 32767, 0, 32767),
    "pen-045e-0c32": (0, 9600, 0, 7200),
    "hybrid-touch": (0, 4095, 0, 4095),
}


def contacts_of(device, values):
    result = []
    if device == "touchpad-045e-09af":
        count = values.get("count", 0)
        for k in range(5):
            key = "contact%d" % k
            if k < count and (key + ".x") in values:
                result.append((values[key + ".id"], values[key + ".x"], values[key + ".y"],
                               values[key + ".tip"], values[key + ".conf"]))
    elif device == "touchscreen-045e-0c32":
        result.append((0, values["x"], values["y"], values["tip"], 1))
    return result


class Tracker:
    def __init__(self, kind, rng, flags):
        self.kind = kind
        self.rng = rng
        self.flags = flags
        self.slots = {}
        self.pen_state = None

    def xy(self, rx, ry):
        xlo, xhi, ylo, yhi = self.rng
        nx = norm(rx, xlo, xhi)
        ny = norm(ry, ylo, yhi)
        if self.flags & Q_INVERT_X:
            nx = NORM_MAX - nx
        if self.flags & Q_INVERT_Y:
            ny = NORM_MAX - ny
        return nx, ny

    def frame(self, contacts, now):
        events = []
        present = {}
        for call, (cid, rx, ry, tip, conf) in enumerate(contacts):
            if self.flags & Q_SINGLE_TOUCH and call > 0:
                continue
            if tip == 0:
                continue
            if cid in present:
                continue
            nx, ny = self.xy(rx, ry)
            fl = F_PALM if conf == 0 else 0
            present[cid] = (nx, ny, fl)
        for slot in sorted(list(self.slots)):
            if self.slots[slot][0] not in present:
                cid, nx, ny, fl = self.slots.pop(slot)
                events.append((T_UP, slot, fl, nx, ny, now))
        for cid, (nx, ny, fl) in present.items():
            if all(v[0] != cid for v in self.slots.values()):
                slot = min(s for s in range(10) if s not in self.slots)
                self.slots[slot] = (cid, nx, ny, fl)
                events.append((T_DOWN, slot, fl, nx, ny, now))
        for slot in sorted(self.slots):
            cid, ox, oy, ofl = self.slots[slot]
            if cid in present:
                nx, ny, fl = present[cid]
                if (nx, ny, fl) != (ox, oy, ofl):
                    self.slots[slot] = (cid, nx, ny, fl)
                    events.append((T_MOVE, slot, fl, nx, ny, now))
        return events

    def pen(self, values, now):
        events = []
        if not values.get("inrange"):
            if self.pen_state is not None:
                x, y, fl = self.pen_state
                events.append((T_UP, 0, fl, x, y, now))
                self.pen_state = None
            return events
        fl = 0
        pr = 0
        if values.get("tip"):
            pr = min(values.get("pressure", 0) * NORM_MAX // 4096, NORM_MAX)
        else:
            fl = F_HOVER
        if values.get("barrel"):
            fl |= F_BARREL
        if values.get("eraser") or values.get("invert"):
            fl |= F_ERASER
        x, y = self.xy(values["x"], values["y"])
        if self.pen_state is None:
            self.pen_state = (x, y, fl)
            self.pen_pr = pr
            events.append((T_DOWN, 0, fl, x, y, now, pr))
            return events
        if self.pen_state != (x, y, fl) or pr != getattr(self, "pen_pr", 0):
            self.pen_state = (x, y, fl)
            events.append((T_MOVE, 0, fl, x, y, now, pr))
        self.pen_pr = pr
        return events


def expected_lines(flags=0, only=None):
    reports = input_reports()
    lines = []
    for d in DEVICES:
        name, vid, pid, kind, _ = d
        if only and name != only:
            continue
        if name == INPUTMODE:
            continue
        tr = Tracker(kind, RANGES[name], flags)
        now = START_MS
        if name == HYBRID:
            batches = [tr.frame(f, START_MS) for f in hybrid_frames(reports[name])]
        else:
            batches = []
            for line in reports[name]:
                now += STEP_MS
                if kind == 3:
                    batches.append(tr.pen(line.values, now))
                else:
                    batches.append(tr.frame(contacts_of(name, line.values), now))
        for evs in batches:
            for e in evs:
                typ, slot, fl, nx, ny, t = e[:6]
                pr = e[6] if len(e) > 6 else 0
                if kind == 2:
                    px = py = 0
                else:
                    px = to_px(nx, SCREEN_W)
                    py = to_px(ny, SCREEN_H)
                lines.append((name, "touchev: %d slot=%d dev=%d fl=%d x=%d y=%d px=%d py=%d p=%d" %
                              (typ, slot, kind, fl, nx, ny, px, py, pr)))
    return lines


def parse_serial(path):
    sections = {}
    quirks = {}
    current = None
    with open(path, "rb") as f:
        for raw in f:
            text = raw.decode("latin-1").rstrip("\r\n")
            m = re.match(r"^corpus: begin (\S+)", text)
            if m:
                current = m.group(1)
                sections.setdefault(current, [])
                continue
            m = re.match(r"^corpus: q=(\d+)", text)
            if m and current is not None:
                quirks[current] = int(m.group(1))
                continue
            m = re.match(r"^corpus: end (\S+)", text)
            if m:
                current = None
                continue
            if current is not None and text.startswith("touchev: ") and "lost=" not in text:
                m2 = re.match(r"^touchev: (\d+) slot=(\d+) dev=(\d+) fl=(\d+) x=(\d+) y=(\d+) px=(\d+) py=(\d+) p=(\d+) sz=(\d+) t=(\d+) a=(-?\d+) b=(-?\d+)$", text)
                if m2:
                    sections[current].append(m2.groups())
    return sections, quirks


def parse_inmode(path):
    out = []
    with open(path, "rb") as f:
        for raw in f:
            text = raw.decode("latin-1").rstrip("\r\n")
            if text.startswith("corpus: inmode ") or text.startswith("corpus: i2c "):
                out.append(text)
    return out


def kernel_raw(section):
    out = []
    for g in section:
        if int(g[0]) in (T_DOWN, T_MOVE, T_UP):
            out.append("touchev: %s slot=%s dev=%s fl=%s x=%s y=%s px=%s py=%s p=%s" %
                       (g[0], g[1], g[2], g[3], g[4], g[5], g[6], g[7], g[8]))
    return out


def compare(path):
    sections, quirks = parse_serial(path)
    ok = 0
    bad = 0

    def check(label, want, got):
        nonlocal ok, bad
        if want == got:
            ok += 1
            if isinstance(want, list):
                print("OK   %s (%d events)" % (label, len(want)))
            else:
                print("OK   %s" % label)
        else:
            bad += 1
            print("FAIL %s" % label)
            if not isinstance(want, list):
                print("   want %s" % (want,))
                print("   got  %s" % (got,))
                return
            for i in range(max(len(want), len(got))):
                w = want[i] if i < len(want) else "-"
                g = got[i] if i < len(got) else "-"
                mark = " " if w == g else "!"
                print("   %s want %s" % (mark, w))
                print("   %s got  %s" % (mark, g))

    for d in DEVICES:
        name = d[0]
        if name == INPUTMODE:
            continue
        want = [l for n, l in expected_lines(0, name)]
        got = kernel_raw(sections.get("dev%d" % DEVICES.index(d), []))
        check("kernel events for %s equal the independent expectation" % name, want, got)
    want = [l for n, l in expected_lines(FAKE_FLAGS, "touchpad-045e-09af")]
    got = kernel_raw(sections.get("quirk-invert", []))
    check("quirk row invert_x|invert_y mirrors both axes (touchpad)", want, got)
    inv_gap = [l for n, l in expected_lines(0, "touchpad-045e-09af")]
    check("the inverted run differs from the plain run", True, inv_gap != want)
    want = [l for n, l in expected_lines(Q_SINGLE_TOUCH, "touchpad-045e-09af")]
    got = kernel_raw(sections.get("quirk-single", []))
    check("quirk row single_touch keeps only the first contact", want, got)
    got = kernel_raw(sections.get("quirk-ignore", []))
    check("quirk row ignore drops every report", [], got)
    check("registry quirk flags per run equal the table rows",
          {"dev0": 0, "dev1": Q_SINGLE_TOUCH, "dev2": Q_SINGLE_TOUCH, "dev4": 0, "quirk-invert": FAKE_FLAGS,
           "quirk-single": Q_SINGLE_TOUCH, "quirk-ignore": Q_IGNORE}, {k: v for k, v in quirks.items() if k != "prime"})
    check("input mode feature reports and their I2C frames equal the spec model", inmode_expected(), parse_inmode(path))
    gest = [g for g in sections.get("dev1", []) if int(g[0]) == 4]
    flags = sorted(set(int(g[3]) for g in gest))
    check("touch screen reports produce gesture records (tap)", True, 1 in flags)
    print("corpus kernel: %d ok, %d fail" % (ok, bad))
    return 0 if bad == 0 else 1


def main(argv):
    if len(argv) >= 2 and argv[1] == "gen":
        print(generate())
        return 0
    if len(argv) >= 2 and argv[1] == "check-gen":
        before = open(OUT_FI).read() if os.path.exists(OUT_FI) else ""
        generate()
        after = open(OUT_FI).read()
        if before != after:
            print("corpusdata.fi was stale and has been regenerated")
            return 1
        print("corpusdata.fi is up to date")
        return 0
    if len(argv) >= 3 and argv[1] == "compare":
        return compare(argv[2])
    print("usage: corpus_kernel.py gen | check-gen | compare SERIAL")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
