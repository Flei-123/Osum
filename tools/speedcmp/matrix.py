import argparse
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from smbudget import ratchet, raised, target_gap, verdict
from smcore import BUDGETS, HEADER, RAW_HEADER, load_budgets, read_tsv, registry, write_tsv
from smmetrics import push

DOC_HEADER = "# Osum vs Linux: speed matrix\n\nGenerated by `tools/speedcmp/gate.sh` (see `docs/speed-howto.md`). All times are microseconds per operation, median of the boots; `ratio` = osum / linux (above 1.0 means Osum is slower); `budget` = highest ratio allowed (ratchet, only goes down); `-` = not gated.\n\n"


def cmd_build(args):
    rows, raw, o_runs, l_runs = build_rows_for(args)
    write_tsv(args.tsv, HEADER, rows)
    if args.raw:
        write_tsv(args.raw, RAW_HEADER, raw)
    if args.md:
        write_md(args.md, rows, o_runs, l_runs, args.notes)
    print_summary(rows, o_runs, l_runs)


def build_rows_for(args):
    from smcore import build_rows
    return build_rows(args.dirs, load_budgets(args.budgets))


def write_md(path, rows, o_runs, l_runs, notes):
    labels = {t: label for t, _, label in registry()}
    lines = ["| Test | Linux us | Osum us | Ratio | Budget | Status |", "|---|---|---|---|---|---|"]
    lines += ["| %s | %s | %s | %s | %s | %s |" % (labels[r[0]], r[1], r[2], r[3], r[4], r[5]) for r in rows]
    with open(path, "w") as handle:
        handle.write(DOC_HEADER + "\n".join(lines) + "\n\nRuns: Osum %d, Linux %d.\n%s\n" % (o_runs, l_runs, notes))


def print_summary(rows, o_runs, l_runs):
    ratios = [float(r[3]) for r in rows if r[3] != ""]
    geo = math.exp(sum(math.log(x) for x in ratios) / len(ratios)) if ratios else 0.0
    counts = {}
    for r in rows:
        counts[r[5]] = counts.get(r[5], 0) + 1
    print("runs osum=%d linux=%d tests=%d geomean_ratio=%.2f %s" % (o_runs, l_runs, len(rows), geo, " ".join("%s=%d" % kv for kv in sorted(counts.items()))))


def cmd_ratchet(args):
    rows = [r for r in read_tsv_rows(args.tsv)]
    out = ratchet(rows, args.budgets)
    print("budgets written: %d" % len(out))


def read_tsv_rows(path):
    return [[r[h] for h in HEADER] for r in read_tsv(path)]


def cmd_gate(args):
    rows = read_tsv_rows(args.tsv)
    red = verdict(rows)
    bad = raised(args.budgets, args.base)
    for test, status, ratio, budget in red:
        print("RED %s status=%s ratio=%s budget=%s" % (test, status, ratio, budget))
    for line in bad:
        print("RED budget raised: " + line)
    print("target gap: %d tests above 1.0" % len(target_gap(rows)))
    return 1 if red or bad else 0


def cmd_red(args):
    for r in read_tsv_rows(args.tsv):
        gated = r[4] not in ("", "-")
        if r[5] == "red" or (gated and r[5] in ("fail", "nodata")):
            print(r[0])


def cmd_metrics(args):
    for line in push(read_tsv_rows(args.tsv)):
        print(line)


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="cmd", required=True)
    build = sub.add_parser("build")
    build.add_argument("dirs", nargs="+")
    build.add_argument("--tsv", required=True)
    build.add_argument("--raw")
    build.add_argument("--md")
    build.add_argument("--notes", default="")
    build.add_argument("--budgets", default=BUDGETS)
    build.set_defaults(fn=cmd_build)
    for name, fn in (("ratchet", cmd_ratchet), ("gate", cmd_gate), ("red", cmd_red), ("metrics", cmd_metrics)):
        p = sub.add_parser(name)
        p.add_argument("tsv")
        p.add_argument("--budgets", default=BUDGETS)
        p.add_argument("--base", default="origin/main")
        p.set_defaults(fn=fn)
    args = parser.parse_args()
    sys.exit(args.fn(args) or 0)


main()
