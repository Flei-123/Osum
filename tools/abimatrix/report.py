import argparse
import collections
import re

import registry

GROUP_ORDER = ("busybox", "coreutils-like", "python3", "curl", "git", "compiled-c", "compiler", "firefox")


def parse_serial(path):
    values, started = {}, []
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.replace("\r", "")
        for m in re.finditer(r"(?<![A-Za-z])AMB ([A-Za-z0-9_-]+)", line):
            started.append(m.group(1))
        m = re.search(r"(?<![A-Za-z])AM ([A-Za-z0-9_-]+)(?: (.*))?$", line)
        if m and m.group(1) not in values:
            values[m.group(1)] = m.group(2) or ""
    return values, started


def parse_ext(path):
    results = {}
    if not path:
        return results
    for line in open(path, encoding="utf-8"):
        fields = line.rstrip("\n").split("\t")
        if len(fields) >= 2:
            results[fields[0]] = (fields[1], fields[2] if len(fields) > 2 else "")
    return results


def judge(row, values, started, ext):
    if row.kind == "skip":
        return "SKIP", row.expected
    if row.kind == "ext":
        return ext.get(row.id, ("SKIP", "external stage not run (ABI_EXT=1 to run)"))
    if row.id not in values:
        last = started[-1] if started else "none"
        return "FAIL", "not run (script stopped; last started row: %s)" % last
    got = values[row.id]
    if row.kind == "eq":
        return ("PASS", got) if got == row.expected else ("FAIL", got)
    return ("PASS", got) if re.search(row.expected, got) else ("FAIL", got)


def load_known_red(path):
    return {l.split()[0] for l in open(path, encoding="utf-8") if l.strip() and not l.startswith("#")}


def cell(text):
    return text.replace("|", "\\|").replace("`", "'")[:90]


def write_tsv(path, table):
    with open(path, "w", encoding="utf-8") as f:
        f.write("id\tgroup\tstatus\texpected\tgot\n")
        for row, status, detail in table:
            f.write("\t".join((row.id, row.group, status, row.expected, detail)) + "\n")


def write_markdown(path, table, title):
    totals = collections.Counter(status for _, status, _ in table)
    groups = collections.OrderedDict()
    for row, status, detail in table:
        groups.setdefault(row.group, []).append((row, status, detail))
    order = sorted(groups, key=lambda g: GROUP_ORDER.index(g) if g in GROUP_ORDER else len(GROUP_ORDER))
    with open(path, "w", encoding="utf-8") as f:
        f.write("# %s\n\nGenerated by `tools/abimatrix/run.sh` (registry: `tools/abimatrix/registry.tsv`). Do not edit by hand.\n\n" % title)
        f.write("**%d PASS / %d FAIL / %d SKIP** of %d programs.\n" % (totals["PASS"], totals["FAIL"], totals["SKIP"], len(table)))
        for group in order:
            f.write("\n## %s\n\n| program | status | expected / reason | got |\n|---|---|---|---|\n" % group)
            for row, status, detail in groups[group]:
                expected = row.expected if row.kind != "ext" else "exit 0"
                shown = detail if status != "SKIP" else ""
                reason = detail if status == "SKIP" else expected
                f.write("| `%s` | %s | %s | %s |\n" % (row.id, status, cell(reason), cell(shown)))


def gate(table, known_red, counter_table):
    problems = []
    for row, status, detail in table:
        if status == "FAIL" and row.id not in known_red:
            problems.append("%s FAIL (new): %s" % (row.id, detail))
        if status == "PASS" and row.id in known_red:
            problems.append("%s PASS but listed in known-red.txt: remove it" % row.id)
    for row, status, detail in counter_table:
        if status != "FAIL":
            problems.append("counter-proof %s did not come out FAIL (%s): the matrix measures nothing" % (row.id, status))
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", required=True)
    ap.add_argument("--counter", required=True)
    ap.add_argument("--serial", required=True)
    ap.add_argument("--ext")
    ap.add_argument("--known-red", required=True)
    ap.add_argument("--tsv", required=True)
    ap.add_argument("--md", required=True)
    args = ap.parse_args()
    values, started = parse_serial(args.serial)
    ext = parse_ext(args.ext)
    table = [(r,) + tuple(judge(r, values, started, ext)) for r in registry.load(args.registry)]
    counter_table = [(r,) + tuple(judge(r, values, started, ext)) for r in registry.load(args.counter)]
    write_tsv(args.tsv, table)
    write_markdown(args.md, table, "Linux ABI matrix: real Linux programs on Osum")
    for line in open(args.tsv, encoding="utf-8").read().splitlines()[1:]:
        fields = line.split("\t")
        print("  %-5s %-28s %-15s %s" % (fields[2], fields[0], fields[1], fields[4][:70] if fields[2] != "PASS" else ""))
    problems = gate(table, load_known_red(args.known_red), counter_table)
    totals = collections.Counter(s for _, s, _ in table)
    print("MATRIX: %d PASS / %d FAIL / %d SKIP; counter-proofs: %d of %d came out FAIL"
          % (totals["PASS"], totals["FAIL"], totals["SKIP"], sum(1 for _, s, _ in counter_table if s == "FAIL"), len(counter_table)))
    for p in problems:
        print("  GATE-FAIL %s" % p)
    checks = len(table) + len(counter_table) - totals["SKIP"]
    print("ABIMATRIX: %d passed, %d failed" % (checks - len(problems), len(problems)))
    raise SystemExit(1 if problems else 0)


if __name__ == "__main__":
    main()
