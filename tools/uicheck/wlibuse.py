#!/usr/bin/env python3
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASELINES = {"wlib": os.path.join(ROOT, "tools", "uicheck", "wlib_baseline.tsv"),
             "wlibc": os.path.join(ROOT, "tools", "uicheck", "wlibc_baseline.tsv")}
DOC = os.path.join(ROOT, "docs", "wlib-migration.md")
DOC_START = "<!-- INVENTORY:START (generated by tools/uicheck/wlibuse.py doc) -->"
DOC_END = "<!-- INVENTORY:END -->"

WLIB_MODULES = ("wlib", "wlax", "wlbase", "wldraw", "wlevent", "wlstate", "wlwidget")
WLIBC_MODULES = ("wlibc", "wcbase", "wcgfx", "wcpaint", "wcpal", "wcstart", "thbase", "thquery", "thfile", "thapply", "thload", "thprobe", "thpush", "thedge")
TOOLKIT_PATHS = ("kernel/user/wlibc/", "kernel/user/uitheme/", "kernel/user/fuiapp/")
TOOLKIT_FILES = {"kernel/user/fuiapp/wlib.fi", "kernel/user/wlibc.fi", "kernel/user/uitheme.fi", "kernel/user/uitext.fi", "kernel/user/uiicon.fi"}
IMPORT = re.compile(rb"^import ([A-Za-z0-9_.]+)", re.M)
REF = re.compile(rb"\b(" + b"|".join(m.encode() for m in WLIB_MODULES + WLIBC_MODULES) + rb")\.([A-Za-z_][A-Za-z0-9_]*)")

CATEGORY_BY_MODULE = {"wcpaint": "draw", "wcgfx": "window", "wcbase": "window", "wcpal": "theme", "wcstart": "window", "thbase": "theme", "thquery": "theme", "thfile": "theme", "thapply": "theme", "thload": "theme", "thprobe": "theme", "thpush": "theme", "thedge": "theme"}

CATEGORY_RULES = (
    ("services", r"^(clip_(put|take|hist|len)|drag_|noti_|bus_)"),
    ("icon", r"^(icon|app_icon|I_)"),
    ("theme", r"^(T_|C_|M_|L_|theme|set_aa_old|aa_old|tb_alpha|tb_blur|set_radius|set_tb|set_win_alpha|"
              r"set_transparency|set_shadow|metric|radius|win_round|transparency|fx_|elev_|type_|space$|shade|"
              r"motion|blur_|platte|pick_on|luminance|contrast|mix$|ramp|grid|snap|hit_min|shape_)"),
    ("text", r"^(text_|F_|glyph|pen_x|ascent_of|chars|fit$|mono_cell|draw_glyph|ink_|kern26|px_mono|gload)"),
    ("draw", r"^(rect|hline|vline|frame|frame3|rrect|rframe|rring|v_|vrect|vkreis|vring|px$|get$|blend|mix8|"
             r"drop_shadow|shadow_edge|divider|plate|clip_set|clip_x|clip_y|sub$|push|back$)"),
    ("window", r"^(win_|W[A-Z]?_|work_|screen_|head_|display_|ready|map_surface|shm_|surface|surf_|band_|"
               r"layer_rank|start|set_head|set_band|ui_scale|px_ui|edge_|cursor_|mouse_|sys)"),
    ("a11y", r"^(ax_|AX_)"),
)
WLIB_SUBMODULE_CATEGORY = {"wlax": "a11y", "wldraw": "draw", "wlevent": "events", "wlstate": "widgets",
                           "wlwidget": "widgets", "wlbase": "widgets"}
REPLACEMENT = {
    "theme": "uitheme roles (planned, today wlibc.theme) / fuiscene.R_*",
    "icon": "fuiscene icon / lib/icons.fi + lib/appicon.fi",
    "text": "fuiscene.label / fscore text metrics",
    "draw": "fuiscene controls, uikit.uisurface (no raw draw in apps)",
    "window": "fuiscene host (fsrun, fuiapp); platform API stays below fuiscene",
    "services": "platform services module (clipboard, drag, notify, bus): move, not UI",
    "a11y": "fuiscene a11y tree (scene nodes)",
    "events": "fuiscene event loop (fsrun)",
    "widgets": "fuiscene controls (button, field, table, menu, dialog, toggle)",
    "keys": "fuiscene key constants",
    "other": "check by hand",
}
COMPONENT_PREFIXES = ("kernel/user/uikit/", "kernel/user/fuiscene/")
COMPONENT_FILES = {"kernel/user/fuiscene.fi", "kernel/user/fuib.fi", "kernel/user/fuiapp.fi"}
ENTRY = re.compile(rb"^(fn main\(|export \{ *u_start\b)", re.M)
OWNERS = {"taskbar": "w-tray-icons / w-taskbar-preview-ram", "settings": "w-settings-win11-confirm",
          "notify": "w-notify-unify", "barpop": "w-notify-unify"}
DEFAULT_OWNER = "w-m4-wlib-migration"


def git_sources(root):
    out = subprocess.run(["git", "ls-files", "kernel", "lib"], cwd=root, capture_output=True, check=True).stdout
    return [l for l in out.decode().splitlines() if l.endswith(".fi")]


def is_toolkit(rel):
    return rel in TOOLKIT_FILES or rel.startswith(TOOLKIT_PATHS)


def facade_symbols(root, rel, sub_default):
    table = {}
    text = open(os.path.join(root, rel), "rb").read().decode("latin-1")
    for m in re.finditer(r"^fn ([A-Za-z0-9_]+)\([^\n]*\n(.*?)^\}", text, re.M | re.S):
        call = re.search(r"\b([a-z0-9_]+)\.[A-Za-z_]", m.group(2))
        table[m.group(1)] = call.group(1) if call else sub_default
    for m in re.finditer(r"^const ([A-Za-z0-9_]+)[^=\n]*= *([a-z0-9_]+\.)?", text, re.M):
        table[m.group(1)] = m.group(2)[:-1] if m.group(2) else sub_default
    return table


def category(module, name, facades):
    if module in WLIB_MODULES:
        sub = facades["wlib"].get(name, "wlib") if module == "wlib" else module
        return WLIB_SUBMODULE_CATEGORY.get(sub, "widgets")
    for cat, rule in CATEGORY_RULES:
        if re.match(rule, name):
            return cat
    sub = facades["wlibc"].get(name, module)
    return CATEGORY_BY_MODULE.get(sub, "other")


def stem_of(rel):
    return os.path.splitext(os.path.basename(rel))[0]


def reach(sources, imports_of):
    by_stem = {}
    for rel in sources:
        by_stem.setdefault(stem_of(rel), []).append(rel)
    seen_by = {}
    for entry in (rel for rel in sources if imports_of[rel][1]):
        stack, seen = [entry], {entry}
        while stack:
            for mod in imports_of[stack.pop()][0]:
                for dep in by_stem.get(mod.split(".")[-1], []):
                    if dep not in seen:
                        seen.add(dep)
                        stack.append(dep)
        for rel in seen:
            seen_by.setdefault(rel, set()).add(stem_of(entry))
    return seen_by


def program_of(rel, programs):
    if rel in COMPONENT_FILES or rel.startswith(COMPONENT_PREFIXES):
        return "components (fuiscene, fuib, fuiapp, uikit)"
    if len(programs) == 1:
        return next(iter(programs))
    if not programs:
        return "unlinked"
    return "shared modules"


def scan(root):
    facades = {"wlib": facade_symbols(root, "kernel/user/fuiapp/wlib.fi", "wlib"),
               "wlibc": facade_symbols(root, "kernel/user/wlibc.fi", "wlibc")}
    sources = git_sources(root)
    imports_of = {}
    rows = []
    for rel in sources:
        data = open(os.path.join(root, rel), "rb").read()
        mods = [m.decode() for m in IMPORT.findall(data)]
        imports_of[rel] = (mods, bool(ENTRY.search(data)))
        if is_toolkit(rel):
            continue
        tk = [m for m in mods if m.split(".")[-1] in WLIB_MODULES + WLIBC_MODULES]
        if not tk:
            continue
        refs = {}
        for mod, name in REF.findall(data):
            key = (mod.decode(), name.decode())
            refs[key] = refs.get(key, 0) + 1
        rows.append({"file": rel, "imports": tk, "refs": refs, "scene": any(m.split(".")[-1] in ("fuiscene", "fuiapp") for m in mods)})
    programs = reach(sources, imports_of)
    importers = {}
    for rel, (mods, _) in imports_of.items():
        for m in mods:
            importers.setdefault(m.split(".")[-1], set()).add(rel)
    for row in rows:
        stem = os.path.splitext(os.path.basename(row["file"]))[0]
        row["used_by"] = sorted(importers.get(stem, set()) - {row["file"]})
        row["programs"] = sorted(programs.get(row["file"], set()))
        cats = {}
        for (mod, name), n in row["refs"].items():
            cat = category(mod, name, facades)
            cats.setdefault(cat, {})[mod + "." + name] = n
        row["cats"] = cats
        row["wlib"] = sum(n for (mod, _), n in row["refs"].items() if mod in WLIB_MODULES)
        row["wlibc"] = sum(n for (mod, _), n in row["refs"].items() if mod in WLIBC_MODULES)
        row["unused"] = [m for m in row["imports"] if not any(k[0] == m.split(".")[-1] for k in row["refs"])]
    return rows


def family_modules(family):
    return WLIB_MODULES if family == "wlib" else WLIBC_MODULES


def family_counts(rows, family):
    mods = family_modules(family)
    counts = {}
    for r in rows:
        imported = [m for m in r["imports"] if m.split(".")[-1] in mods]
        if not imported:
            continue
        refs = sum(n for (mod, _), n in r["refs"].items() if mod in mods)
        unused = sum(1 for m in r["unused"] if m.split(".")[-1] in mods)
        counts[r["file"]] = refs + unused + len(imported)
    return counts


def read_baseline(family):
    base = {}
    for line in open(BASELINES[family], encoding="utf-8"):
        line = line.rstrip("\n")
        if line and not line.startswith("#"):
            rel, n = line.split("\t")
            base[rel] = int(n)
    return base


def compare(counts, base, family="wlib"):
    bad = 0
    for rel, n in sorted(counts.items()):
        allowed = base.get(rel, 0)
        if n > allowed:
            print("RATCHET %s: %s score %d, allowed %d (use fuiscene)" % (rel, family, n, allowed))
            bad += 1
        elif n < allowed:
            print("SHRUNK  %s: %s score %d < baseline %d (run update)" % (rel, family, n, allowed))
            bad += 1
    for rel in sorted(set(base) - set(counts)):
        print("SHRUNK  %s: 0 < baseline %d (run update)" % (rel, base[rel]))
        bad += 1
    return bad


def update(counts, family):
    path = BASELINES[family]
    if os.path.exists(path):
        old = read_baseline(family)
        for rel, n in counts.items():
            if n > old.get(rel, 0):
                sys.exit("refusing to grow baseline: %s" % rel)
    with open(path, "w", encoding="utf-8") as f:
        f.write("# file\t%s score = imports + refs + unused imports (may only shrink, docs/wlibc-migration.md)\n" % family)
        for rel in sorted(counts):
            f.write("%s\t%d\n" % (rel, counts[rel]))
    print("%s baseline: %d files, score %d" % (family, len(counts), sum(counts.values())))


def priority(row):
    if row["used_by"]:
        return "P3 shared"
    if row["unused"] or row["wlib"] + row["wlibc"] <= 10:
        return "P1 leaf small"
    return "P2 leaf"


def symbols_cell(syms):
    names = sorted(syms, key=lambda s: -syms[s])
    short = [s.split(".", 1)[1] for s in names[:8]]
    more = len(names) - len(short)
    return " ".join(short) + (" +%d" % more if more > 0 else "")


def doc_block(rows):
    out = [DOC_START, ""]
    files = len(rows)
    wl = sum(1 for r in rows if any(m.split(".")[-1] in WLIB_MODULES for m in r["imports"]))
    totals = {}
    for r in rows:
        for cat, syms in r["cats"].items():
            totals[cat] = totals.get(cat, 0) + sum(syms.values())
    out.append("Files importing the toolkit: **%d** (wlib family: %d, wlibc family only: %d). References: %s." % (
        files, wl, files - wl, ", ".join("%s %d" % (c, totals[c]) for c in sorted(totals, key=lambda c: -totals[c]))))
    out.append("")
    out.append("| category | replacement |")
    out.append("|---|---|")
    for cat in sorted(totals, key=lambda c: -totals[c]):
        out.append("| %s | %s |" % (cat, REPLACEMENT[cat]))
    by_prog = {}
    for r in rows:
        by_prog.setdefault(program_of(r["file"], r["programs"]), []).append(r)
    for prog in sorted(by_prog, key=lambda p: (-sum(x["wlib"] + x["wlibc"] for x in by_prog[p]), p)):
        out.append("")
        out.append("### %s (owner: %s)" % (prog, OWNERS.get(prog, DEFAULT_OWNER)))
        out.append("")
        out.append("| file | prio | wlib / wlibc refs | scene | unused imports | importers / programs | symbols by category |")
        out.append("|---|---|---|---|---|---|---|")
        for r in sorted(by_prog[prog], key=lambda x: x["file"]):
            cats = "; ".join("**%s** %s" % (c, symbols_cell(r["cats"][c])) for c in sorted(r["cats"]))
            progs = " ".join(r["programs"]) if 0 < len(r["programs"]) <= 3 else str(len(r["programs"]))
            used = "%d / %s" % (len(r["used_by"]), progs)
            out.append("| `%s` | %s | %d / %d | %s | %s | %s | %s |" % (
                r["file"][len("kernel/"):], priority(r), r["wlib"], r["wlibc"], "yes" if r["scene"] else "no",
                " ".join(r["unused"]) or "-", used, cats or "-"))
    out.append("")
    out.append(DOC_END)
    return "\n".join(out)


def write_doc(rows):
    text = open(DOC, encoding="utf-8").read()
    head, rest = text.split(DOC_START, 1)
    tail = rest.split(DOC_END, 1)[1]
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(head + doc_block(rows) + tail)
    print("doc: %d files" % len(rows))


def selftest(rows):
    ok = True
    for family in BASELINES:
        counts = family_counts(rows, family)
        probe = dict(counts)
        victim = sorted(counts)[0] if counts else "kernel/user/selftest_probe.fi"
        probe[victim] = probe.get(victim, 0) + 1
        grown = compare(probe, read_baseline(family), family) > 0
        print("%s selftest: grown file flagged %s" % (family, grown))
        ok = ok and grown
    sample = b"wlib.button(1)\nwlibc.theme(wlibc.T_BG)\nfuiscene.label(x)\nwlstate.focus()\n"
    found = len([m for m in REF.findall(sample) if m[0].decode() in WLIB_MODULES])
    print("wlib selftest: sample wlib refs %d (want 2)" % found)
    return 0 if ok and found == 2 else 1


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    rows = scan(ROOT)
    if mode == "update":
        for family in BASELINES:
            update(family_counts(rows, family), family)
        return
    if mode == "doc":
        write_doc(rows)
        return
    if mode == "selftest":
        sys.exit(selftest(rows))
    failed = False
    for family in BASELINES:
        counts = family_counts(rows, family)
        bad = compare(counts, read_baseline(family), family)
        print("%s ratchet: %d files, score %d, %s" % (family, len(counts), sum(counts.values()),
                                                      "ok" if bad == 0 else "%d problems" % bad))
        failed = failed or bad > 0
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
