import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
KIB = 1024


def load_plan():
    plan = {}
    with open(os.path.join(HERE, "plan.tsv")) as handle:
        for line in handle:
            name, kind, state, why = line.rstrip("\n").split("\t")
            plan[name] = (kind, state, why)
    return plan


def load_sizes(elf_dir):
    sizes = {}
    for path in glob.glob(os.path.join(elf_dir, "*.elf")):
        sizes[os.path.basename(path)[:-4]] = os.path.getsize(path) // KIB
    return sizes


def recipe_value(path, key):
    with open(path) as handle:
        for line in handle:
            if line.startswith(key + "="):
                return line.split("=", 1)[1].strip()
    return ""


def payload_kib(recipe):
    total = 0
    base = os.path.dirname(recipe)
    with open(recipe) as handle:
        for line in handle:
            if not line.startswith("datei="):
                continue
            source = line.split("=", 1)[1].split()[-1]
            path = os.path.join(base, source)
            if os.path.isfile(path):
                total += os.path.getsize(path) // KIB
    return total


def program_rows(plan, sizes):
    rows = []
    for name in sorted(sizes, key=lambda n: (-sizes[n], n)):
        kind, state, why = plan.get(name, ("base", "unlisted", ""))
        rows.append("| %s | %d | %s | %s | %s |" % (name, sizes[name], kind, state, why))
    return rows


def archive_rows(sizes):
    rows = []
    for recipe in sorted(glob.glob(os.path.join(ROOT, "pakete", "*", "rezept"))):
        name = recipe_value(recipe, "name")
        version = recipe_value(recipe, "version")
        payload = payload_kib(recipe) or sizes.get(os.path.basename(os.path.dirname(recipe)), 0)
        rows.append("| %s | %s | %s | pakete/%s |" % (name, version, payload or "-", os.path.basename(os.path.dirname(recipe))))
    return rows


def main():
    elf_dir = sys.argv[1]
    plan = load_plan()
    sizes = load_sizes(elf_dir)
    totals = {}
    for name, size in sizes.items():
        kind = plan.get(name, ("base",))[0]
        totals[kind] = totals.get(kind, 0) + size
    print("# Package inventory\n")
    print("Generated by `python3 tools/pkginv/table.py <elf-dir>` from `tools/pkginv/plan.tsv` and the ELF sizes of one image build.")
    print("Criterion: a program stays in the base image only when boot, login, update or recovery need it; everything else is a signed package (opk).\n")
    print("Sizes in KiB. kind: base / package / dev (dev profile only). state: keep, plan (package route planned), done (package exists or dev-only).\n")
    print("Totals (KiB): " + ", ".join("%s %d" % (k, totals[k]) for k in sorted(totals)) + "\n")
    print("## Programs in /bin\n")
    print("| name | KiB | kind | state | reason |\n|---|---|---|---|---|")
    print("\n".join(program_rows(plan, sizes)))
    print("\n## Package archives (pakete/)\n")
    print("| package | version | payload KiB | recipe |\n|---|---|---|---|")
    print("\n".join(archive_rows(sizes)))


main()
