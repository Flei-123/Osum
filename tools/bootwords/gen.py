import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DOC = os.environ.get("BOOTWORDS_DOC") or os.path.join(ROOT, "docs", "bootwords.md")
GATES = os.path.join(ROOT, "tools", "qa", "gates.tsv")
VAR_RE = re.compile(rb'var (\w+): \[u8; \d+\] = "([^"\\]*)(?:\\0)*"')
USE_RE = re.compile(rb'(?:cmdword\.\w+|has_word|k_word|k_number|k_place|num_nach)\(\s*\w+,\s*\(&(\w+)\[0\]\)')
WORD_RE = re.compile(r"^[a-z0-9_=.-]+$")
DESC_LIMIT = 160


def source_files():
    for base, _, names in os.walk(os.path.join(ROOT, "kernel")):
        for name in names:
            if name.endswith(".fi"):
                yield os.path.join(base, name)


def collect_words():
    found = {}
    for path in source_files():
        data = open(path, "rb").read()
        if b"(&" not in data:
            continue
        decls = [(m.start(), m.group(1), m.group(2)) for m in VAR_RE.finditer(data)]
        rel = os.path.relpath(path, ROOT)
        for use in USE_RE.finditer(data):
            name = use.group(1)
            prior = [d for d in decls if d[1] == name and d[0] < use.start()]
            word = prior[-1][2].decode("ascii", "replace").strip(" \x00") if prior else ""
            if word and WORD_RE.match(word):
                found.setdefault(word, set()).add(rel)
    return found


def load_gates():
    rows = []
    with open(GATES, encoding="utf-8") as handle:
        next(handle)
        for line in handle:
            cols = line.rstrip("\n").split("\t")
            if len(cols) >= 6:
                rows.append((cols[0], cols[5], cols[3]))
    return rows


def mentions(word, text):
    bare = word.rstrip("=")
    return re.search(r"(?<![\w-])" + re.escape(bare) + r"(?![\w-])", text) is not None


def describe(word, gates):
    names = []
    desc = ""
    for name, note, paths in gates:
        if name == word.rstrip("="):
            names.insert(0, name)
            desc = desc or note
        elif mentions(word, note):
            names.append(name)
            if not desc and "word" in note:
                desc = note
    desc = desc.split(";", 1)[1].strip() if ";" in desc else ""
    return names[:4], desc[:DESC_LIMIT].replace("|", "/")


def render():
    gates = load_gates()
    words = collect_words()
    lines = [
        "# Kernel boot words",
        "",
        "Generated by `tools/bootwords/gen.py`; do not edit. Check with `tools/bootwords/run.sh`.",
        "",
        f"Total: {len(words)}",
        "",
        "| Word | Parsed in | Gates | Notes |",
        "|---|---|---|---|",
    ]
    for word in sorted(words):
        names, desc = describe(word, gates)
        files = ", ".join(sorted(os.path.basename(p) for p in words[word]))
        lines.append(f"| `{word}` | {files} | {', '.join(names)} | {desc} |")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(DOC, encoding="utf-8").read() if os.path.exists(DOC) else ""
        sys.exit(0 if current == text else 1)
    open(DOC, "w", encoding="utf-8").write(text)


main()
